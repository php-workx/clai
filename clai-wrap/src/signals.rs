    #[test]
    fn test_multiple_signals() {
        let handler = SignalHandler::new().expect("Failed to create signal handler");

        // Send multiple signals
        // SAFETY: Sending these signals to ourselves is safe.
        #[allow(unsafe_code)]
        unsafe {
            libc::kill(libc::getpid(), SIGWINCH);
            libc::kill(libc::getpid(), SIGCHLD);
            libc::kill(libc::getpid(), SIGCONT);
        }

        // Wait a bit for signals to be processed
        thread::sleep(Duration::from_millis(100));

        // Collect all received events
        let mut events = Vec::new();
        while let Ok(Some(event)) = handler.try_recv() {
            events.push(event);
        }

        // Should have received at least one signal
        // (order may vary, and signals may coalesce)
        assert!(!events.is_empty());

        drop(handler);
    }

    #[test]
    fn test_sigquit_ignored() {
        let handler = SignalHandler::new().expect("Failed to create signal handler");

        // Drain any pending signals first
        thread::sleep(Duration::from_millis(50));
        while handler.try_recv().is_ok_and(|e| e.is_some()) {}

        // Record the time before sending SIGQUIT
        let before = std::time::Instant::now();

        // SIGQUIT should be ignored - sending it should not terminate the process
        // SAFETY: Sending SIGQUIT to ourselves when it's ignored is safe.
        #[allow(unsafe_code)]
        unsafe {
            libc::kill(libc::getpid(), SIGQUIT);
        }

        // If we get here, SIGQUIT was successfully ignored (didn't terminate the process)
        // That's the main thing we're testing. The fact that we reach this line proves
        // SIGQUIT is being ignored.
        assert!(
            before.elapsed() < Duration::from_secs(1),
            "Test completed successfully"
        );

        drop(handler);
    }

