    // Note: We cannot easily test SIGINT/SIGTERM without risking test termination,
    // but we verify they are registered by checking that the handler initializes
    // successfully and that our signal mapping is correct.

    #[test]
    fn test_signal_mapping() {
        // Verify our signal constants are what we expect
        assert_eq!(SIGWINCH, libc::SIGWINCH);
        assert_eq!(SIGCHLD, libc::SIGCHLD);
        assert_eq!(SIGINT, libc::SIGINT);
        assert_eq!(SIGTERM, libc::SIGTERM);
        assert_eq!(SIGHUP, libc::SIGHUP);
        assert_eq!(SIGTSTP, libc::SIGTSTP);
        assert_eq!(SIGCONT, libc::SIGCONT);
        assert_eq!(SIGQUIT, libc::SIGQUIT);
        assert_eq!(SIGPIPE, libc::SIGPIPE);
    }
