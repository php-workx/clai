    #[test]
    fn test_events_receiver() {
        let handler = SignalHandler::new().expect("Failed to create signal handler");
        let receiver = handler.events();

        // Send a signal
        // SAFETY: Sending SIGWINCH to ourselves is safe.
        #[allow(unsafe_code)]
        unsafe {
            libc::kill(libc::getpid(), SIGWINCH);
        }

        // Wait for any signal to arrive via the receiver reference
        thread::sleep(Duration::from_millis(50));

        // Just verify we can receive through the receiver reference
        // We may get our SIGWINCH or a signal from another test
        let mut received_something = false;
        let deadline = std::time::Instant::now() + Duration::from_millis(200);
        while std::time::Instant::now() < deadline {
            if receiver.try_recv().is_ok() {
                received_something = true;
                break;
            }
            thread::sleep(Duration::from_millis(10));
        }

        assert!(
            received_something,
            "Expected to receive at least one signal through events() receiver"
        );

        drop(handler);
    }

